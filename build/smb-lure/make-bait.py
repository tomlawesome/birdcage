#!/usr/bin/env python3
"""Generate the SMB lure's share content from the templates beside it.

Issue #87, decision 8: a few directories and files whose names promise
something, generated at build from templates with fabricated contents,
each under 100 KB.

Nothing here is real, and nothing here ever can be. The templates in
bait/ are invented: invented staff references with no names, invented
router settings on the RFC 5737 documentation address ranges, invented
contract clauses. None of them contains a credential, a key, a token or
anything shaped like one -- not a placeholder that looks like a working
value either. A file that promises credentials by its *name* is what
makes somebody open it, and opening it is the whole alarm; putting
anything real, or anything resembling real, inside it would only add a
way for this container to hurt the operator who deployed it. See
README.md, "Why nothing real is ever on the share".

This runs in a build stage that is discarded, so its Python is never in
the shipped image.

Usage: make-bait.py <template dir> <output dir>

Naming rule, which is the whole of the template language:

    foo.pdf.txt   ->  foo.pdf    the text, typeset into a valid PDF
    foo.xlsx.tsv  ->  foo.xlsx   the tab-separated rows, as a valid xlsx
    foo.txt       ->  foo.txt    copied verbatim

Wrapping the text in the real container format matters for one reason
only: a file named .pdf that is not a PDF is a tell. It is a tell that
costs nothing to remove, so it is removed.
"""
import io
import os
import sys
import zipfile
from xml.sax.saxutils import escape

# Decision 8's own ceiling. Enforced here rather than trusted: a template
# that grows past it should fail the build, not quietly ship.
MAX_BYTES = 100 * 1024

# PDF page geometry, in PostScript points: ISO A4, a 56pt margin, 10pt
# Courier on 12pt leading.
PAGE_W, PAGE_H = 595, 842
MARGIN = 56
FONT_SIZE = 10
LEADING = 12
LINES_PER_PAGE = (PAGE_H - 2 * MARGIN) // LEADING
# Courier is a fixed-width face 0.6 em wide, so a 10pt line fits
# (page width - margins) / 6 characters.
COLS_PER_LINE = (PAGE_W - 2 * MARGIN) // (FONT_SIZE * 3 // 5)


def wrap(text):
    """Break text into printable lines, hard-wrapping over-long ones."""
    out = []
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line:
            out.append("")
            continue
        while len(line) > COLS_PER_LINE:
            cut = line.rfind(" ", 0, COLS_PER_LINE)
            if cut <= 0:
                cut = COLS_PER_LINE
            out.append(line[:cut].rstrip())
            line = line[cut:].lstrip()
        out.append(line)
    return out


def pdf_string(line):
    """Escape one line for a PDF literal string."""
    return line.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def make_pdf(text):
    """Return text as a single-file PDF with a correct cross-reference table.

    Hand-built rather than generated by a library: the whole document is
    a catalogue, a page tree, one content stream per page and one base-14
    font, and writing those out directly keeps this build stage down to
    the Python standard library.
    """
    lines = wrap(text)
    pages = [lines[i:i + LINES_PER_PAGE] for i in range(0, len(lines), LINES_PER_PAGE)] or [[]]

    # Object numbering: 1 catalogue, 2 page tree, 3 font, then a page
    # object and a content stream for each page.
    first_page_obj = 4
    page_refs = [first_page_obj + 2 * i for i in range(len(pages))]

    objects = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        2: ("<< /Type /Pages /Count %d /Kids [%s] >>"
            % (len(pages), " ".join("%d 0 R" % n for n in page_refs))).encode("ascii"),
        3: b"<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>",
    }

    for i, page_lines in enumerate(pages):
        page_obj = page_refs[i]
        stream_obj = page_obj + 1
        body = ["BT", "/F1 %d Tf" % FONT_SIZE, "%d TL" % LEADING,
                "1 0 0 1 %d %d Tm" % (MARGIN, PAGE_H - MARGIN - FONT_SIZE)]
        for line in page_lines:
            body.append("(%s) Tj T*" % pdf_string(line))
        body.append("ET")
        stream = ("\n".join(body) + "\n").encode("latin-1", "replace")
        objects[page_obj] = (
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %d %d] "
            "/Resources << /Font << /F1 3 0 R >> >> /Contents %d 0 R >>"
            % (PAGE_W, PAGE_H, stream_obj)).encode("ascii")
        objects[stream_obj] = (b"<< /Length %d >>\nstream\n" % len(stream)
                               + stream + b"endstream")

    out = bytearray(b"%PDF-1.4\n")
    offsets = {}
    for num in sorted(objects):
        offsets[num] = len(out)
        out += b"%d 0 obj\n" % num + objects[num] + b"\nendobj\n"

    xref_at = len(out)
    highest = max(objects)
    out += b"xref\n0 %d\n" % (highest + 1)
    out += b"0000000000 65535 f \n"
    for num in range(1, highest + 1):
        out += b"%010d 00000 n \n" % offsets[num]
    out += (b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
            % (highest + 1, xref_at))
    return bytes(out)


def make_xlsx(tsv):
    """Return tab-separated rows as a minimal, valid single-sheet xlsx.

    Inline strings (t="inlineStr"), so there is no shared-string table to
    keep consistent -- every cell carries its own text.
    """
    rows = []
    for r, raw in enumerate(tsv.splitlines(), start=1):
        if not raw.strip():
            continue
        cells = []
        for c, value in enumerate(raw.split("\t")):
            ref = "%s%d" % (column_name(c), r)
            cells.append('<c r="%s" t="inlineStr"><is><t xml:space="preserve">%s</t></is></c>'
                         % (ref, escape(value)))
        rows.append('<row r="%d">%s</row>' % (r, "".join(cells)))

    sheet = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
             '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
             '<sheetData>%s</sheetData></worksheet>' % "".join(rows))
    content_types = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
        '<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
        '</Types>')
    root_rels = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
        '</Relationships>')
    workbook = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
        'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
        '<sheets><sheet name="Sheet1" sheetId="1" r:id="rId1"/></sheets></workbook>')
    workbook_rels = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>'
        '</Relationships>')

    buf = io.BytesIO()
    # A fixed timestamp for every member: the image should build to the
    # same bytes twice running, and a zip that carries the build clock
    # does not.
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in (("[Content_Types].xml", content_types),
                           ("_rels/.rels", root_rels),
                           ("xl/workbook.xml", workbook),
                           ("xl/_rels/workbook.xml.rels", workbook_rels),
                           ("xl/worksheets/sheet1.xml", sheet)):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    return buf.getvalue()


def column_name(index):
    """0 -> A, 25 -> Z, 26 -> AA."""
    name = ""
    index += 1
    while index:
        index, rem = divmod(index - 1, 26)
        name = chr(ord("A") + rem) + name
    return name


def main(argv):
    if len(argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    src, dst = argv[1], argv[2]

    written = 0
    for root, _dirs, files in os.walk(src):
        rel = os.path.relpath(root, src)
        out_dir = dst if rel == "." else os.path.join(dst, rel)
        os.makedirs(out_dir, exist_ok=True)
        for name in sorted(files):
            in_path = os.path.join(root, name)
            if name.endswith(".pdf.txt"):
                out_name = name[: -len(".txt")]
                with open(in_path, "r", encoding="utf-8") as fh:
                    data = make_pdf(fh.read())
            elif name.endswith(".xlsx.tsv"):
                out_name = name[: -len(".tsv")]
                with open(in_path, "r", encoding="utf-8") as fh:
                    data = make_xlsx(fh.read())
            else:
                out_name = name
                with open(in_path, "rb") as fh:
                    data = fh.read()

            if len(data) > MAX_BYTES:
                print("make-bait: %s would be %d bytes, over the %d byte ceiling"
                      % (os.path.join(rel, out_name), len(data), MAX_BYTES),
                      file=sys.stderr)
                return 1

            out_path = os.path.join(out_dir, out_name)
            with open(out_path, "wb") as fh:
                fh.write(data)
            os.chmod(out_path, 0o444)
            written += 1

    if written == 0:
        print("make-bait: no templates found under %s" % src, file=sys.stderr)
        return 1
    print("make-bait: wrote %d file(s) under %s" % (written, dst))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
